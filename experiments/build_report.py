"""
Fill a markdown template with generated tables and numbers, so that no
figure in a report is typed by hand.

Placeholders
    {{T:name}}             -> results/experiments/tables/name.md
    {{S:a::b::c}}          -> value at that key path in results/experiments/summary.json
    {{S:a::b::c|+.0f}}     -> same, with a Python format spec
    {{A:a::0::c}}          -> value from results/audit/audit_original.json (list index allowed)
    {{F:a::b|.3f}}         -> value from results/forecast_reevaluation.json

    python -m experiments.build_report
"""
import json
import os
import re

SOURCES = {"S": os.path.join("results", "experiments", "summary.json"),
           "A": os.path.join("results", "audit", "audit_original.json"),
           "F": os.path.join("results", "forecast_reevaluation.json")}
TEMPLATES = {os.path.join("docs", "templates", "EXPERIMENT_RESULTS.template.md"): "EXPERIMENT_RESULTS.md",
             os.path.join("docs", "templates", "CORRECTIONS_REPORT.template.md"): "CORRECTIONS_REPORT.md",
             os.path.join("docs", "templates", "GUIDE_PRESENTATION_NOTES.template.md"): "GUIDE_PRESENTATION_NOTES.md",
             os.path.join("docs", "templates", "ORIGINAL_VS_IMPROVED.template.md"): "ORIGINAL_VS_IMPROVED.md"}


def build(template_path, out_path, data):
    text = open(template_path).read()

    def table(m):
        with open(os.path.join("results", "experiments", "tables", m.group(1) + ".md")) as f:
            return f.read().strip()

    def value(m):
        src, path, fmt = m.group(1), m.group(2), m.group(3)
        obj = data[src]
        parts = path.split("::")
        for part in parts:
            obj = obj[int(part)] if isinstance(obj, list) else obj[part]
        return format(obj, fmt) if fmt else str(obj)

    text = re.sub(r"\{\{T:([A-Za-z0-9_]+)\}\}", table, text)
    text = re.sub(r"\{\{([SAF]):([^}|]+)(?:\|([^}]+))?\}\}", value, text)
    left = re.findall(r"\{\{[^}]*\}\}", text)
    if left:
        raise ValueError(f"unfilled placeholders in {template_path}: {left[:5]}")
    header = (f"<!-- GENERATED by `python -m experiments.build_report` from {template_path}. "
              "Edit the template, not this file. -->\n")
    with open(out_path, "w") as f:
        f.write(header + text)
    print("written", out_path)


def main():
    data = {k: json.load(open(p)) for k, p in SOURCES.items() if os.path.exists(p)}
    for tpl, out in TEMPLATES.items():
        if os.path.exists(tpl):
            build(tpl, out, data)


if __name__ == "__main__":
    main()
